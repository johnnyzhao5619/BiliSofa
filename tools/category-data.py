"""Generate bounded category facts for TypeScript and C, never execute outside JS."""
from pathlib import Path
import json,re,sys
ROOT=Path(__file__).resolve().parents[1]
v=json.loads((ROOT/'packages/contracts/data/categories.json').read_text());rows=v['categories']
if v['schema']!=1 or len(rows)!=14 or len({r['id'] for r in rows})!=14:raise SystemExit('Category facts mismatch')
for row in rows:
 if set(row)!={'id','label','route'} or type(row['id'])!=int or not 1000<row['id']<1100 or not isinstance(row['label'],str) or not 1<=len(row['label'])<=12 or not re.fullmatch('[a-z_]{1,32}',row['route']):raise SystemExit('Invalid category fact')
ts='// Generated by tools/category-data.py from categories.json; do not edit.\nexport const PUBLIC_CATEGORIES = '+json.dumps(rows,ensure_ascii=False,separators=(',',':'))+' as const;\n'
h='/* Generated category ID allowlist. No external URL/header input. */\nstatic int catalog_category_id(const char *value) {\n'
for r in rows:h+='  if (!strcmp(value, "'+str(r['id'])+'")) return '+str(r['id'])+';\n'
h+='  return 0;\n}\n'
for name,data in [('packages/contracts/src/category-data.ts',ts),('platform/wasm-network/src/catalog-categories.h',h)]:
 path=ROOT/name
 if '--check' in sys.argv:
  if not path.exists() or path.read_text()!=data:raise SystemExit('Stale generated category facts')
 else:path.write_text(data)
print('Category facts validated (14 current official ranking entries)')
