"""Generate address-free C slots from the packaged backend profile schema.

Only stable slot IDs and bounds enter native code. The values are supplied by
the selected local JSON profile at runtime, before main() and cookie import.
"""
from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parents[1]
PROFILE = ROOT / 'apps/tv/service-providers/bilibili-web.json'
HEADER = ROOT / 'platform/wasm-network/src/service-config.h'


def render():
    profile = json.loads(PROFILE.read_text())
    keys = profile['nativeKeys']
    if not 1 <= len(keys) <= 256 or keys != sorted(set(keys)):
        raise SystemExit('Invalid native service slot order')
    if any(not isinstance(profile['strings'][key], str) or not 1 <= len(profile['strings'][key].encode('ascii')) <= 511 for key in keys):
        raise SystemExit('Invalid service slot value')
    lines = ['/* Generated by tools/service-config.py; values stay in packaged JSON. */',
             '#ifndef BILISOFA_SERVICE_CONFIG_H', '#define BILISOFA_SERVICE_CONFIG_H',
             '#ifndef _GNU_SOURCE', '#define _GNU_SOURCE', '#endif',
             '#include <stddef.h>', '#include <string.h>',
             '#ifdef __EMSCRIPTEN__', '#include <emscripten/emscripten.h>',
             '#define SERVICE_EXPORT EMSCRIPTEN_KEEPALIVE', '#else', '#define SERVICE_EXPORT', '#endif',
             f'#define SERVICE_CONFIG_COUNT {len(keys)}', '#define SERVICE_CONFIG_WIDTH 512',
             'static char service_values[SERVICE_CONFIG_COUNT][SERVICE_CONFIG_WIDTH];',
             'static unsigned char service_config_input[SERVICE_CONFIG_COUNT * SERVICE_CONFIG_WIDTH];',
             'static int service_config_ready;',
             'static const unsigned int service_key_words[SERVICE_CONFIG_COUNT][2] = {' + ','.join('{' + str(int(key[2:8], 16)) + ',' + str(int(key[8:14], 16)) + '}' for key in keys) + '};',
             'SERVICE_EXPORT int service_config_count(void) { return SERVICE_CONFIG_COUNT; }',
             'SERVICE_EXPORT int service_config_key_word(int i, int part) { return i >= 0 && i < SERVICE_CONFIG_COUNT && part >= 0 && part < 2 ? (int)service_key_words[i][part] : -1; }',
             'SERVICE_EXPORT int service_config_pointer(void) { return (int)(size_t)service_config_input; }',
             'SERVICE_EXPORT int service_config_capacity(void) { return (int)sizeof(service_config_input); }',
             'SERVICE_EXPORT int service_config_apply(int length) {',
             '  if (service_config_ready || length < 1 || (size_t)length > sizeof(service_config_input)) return 0;',
             '  size_t offset = 0, starts[SERVICE_CONFIG_COUNT], sizes[SERVICE_CONFIG_COUNT];',
             '  for (unsigned i = 0; i < SERVICE_CONFIG_COUNT; i++) {',
             '    if (offset >= (size_t)length) return 0;',
             '    unsigned char *end = memchr(service_config_input + offset, 0, (size_t)length - offset);',
             '    if (!end) return 0;',
             '    size_t n = (size_t)(end - service_config_input) - offset;',
             '    if (!n || n >= SERVICE_CONFIG_WIDTH) return 0;',
             '    for (size_t j = offset; j < offset + n; j++) if (service_config_input[j] < 32 || service_config_input[j] > 126) return 0;',
             '    starts[i] = offset; sizes[i] = n; offset += n + 1;',
             '  }',
             '  if (offset != (size_t)length) return 0;',
             '  for (unsigned i = 0; i < SERVICE_CONFIG_COUNT; i++) memcpy(service_values[i], service_config_input + starts[i], sizes[i] + 1);',
             '  memset(service_config_input, 0, sizeof(service_config_input)); service_config_ready = 1; return 1;',
             '}']
    lines += [f'#define SERVICE_ADDRESS_{key.upper()} service_values[{i}]' for i, key in enumerate(keys)]
    return '\n'.join(lines + ['#endif', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = render()
    if args.check:
        if HEADER.read_text() != content:
            raise SystemExit('Service header/schema drift; run tools/service-config.py')
        print('Service configuration slot schema matches')
    else:
        HEADER.write_text(content)
        print('Generated address-free native service configuration slots')
